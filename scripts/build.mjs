import { build } from 'esbuild';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
const template=await readFile('ui/index.html','utf8'),css=await readFile('ui/style.css','utf8');
await mkdir('cache_monitor/web',{recursive:true});
const result=await build({entryPoints:['ui/app.js'],bundle:true,write:false,format:'iife',platform:'browser',target:['es2022'],minify:true,metafile:true,legalComments:'inline'});
const js=result.outputFiles[0].text.replace(/<\/script/gi,'<\\/script');
const html=template.replace('/* MONITOR_CSS */',()=>css).replace('/* MONITOR_JS */',()=>js);
await writeFile('cache_monitor/web/mcp-app.html',html);
const packageRoots = [...new Set(Object.keys(result.metafile.inputs).map(path =>
  path.replaceAll('\\', '/').match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//)?.[1]).filter(Boolean))].sort();
let notices = '# Third-party components\n\nGauge is licensed under MIT. The following dependency licenses apply to code bundled into the MCP UI. This file is generated by `npm run build` from the actual bundle inputs. Python dependencies are installed separately and retain their own licenses; versions are recorded in `uv.lock`. Product names identify compatibility and do not imply endorsement.\n';
for (const root of packageRoots) {
  const pkg = JSON.parse(await readFile(`${root}/package.json`, 'utf8'));
  let license;
  for (const file of ['LICENSE', 'LICENSE.md', 'LICENSE.txt']) {
    try {license = await readFile(`${root}/${file}`, 'utf8');break;} catch (error) {if (error.code !== 'ENOENT') throw error;}
  }
  if (!license) throw new Error(`Missing bundled dependency license: ${pkg.name}`);
  notices += `\n## ${pkg.name} ${pkg.version}\n\n${license.trim()}\n`;
}
await writeFile('THIRD_PARTY_NOTICES.md',notices);
console.log(`Built mcp-app.html: ${Math.round(Buffer.byteLength(html)/1024)} KiB`);
